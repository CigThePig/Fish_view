function entry({
  activity,
  label,
  status,
  policy,
  visualSentence,
  cues,
  nearestNeighbors,
  owner,
  note,
}) {
  return Object.freeze({
    activity,
    label,
    status,
    policy,
    visualSentence,
    cues: Object.freeze([...cues]),
    nearestNeighbors: Object.freeze([...nearestNeighbors]),
    owner,
    note,
  });
}

